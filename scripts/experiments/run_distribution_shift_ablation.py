def _load_fold(family: str) -> Dict[str, object]:
    return json.loads((FOLDS_DIR / f"{family}.json").read_text(encoding="utf-8"))


def _load_split_map(family: str) -> Dict[str, str]:
    return json.loads((FOLDS_DIR / f"{family}_family_split_map.json").read_text(encoding="utf-8"))


def _load_train_manifest(family: str) -> List[Dict[str, str]]:
    import csv
    fold = _load_fold(family)
    with open(fold["train_manifest"], newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _scalar_model_family(seed: int) -> Dict[str, object]:
    return {
        "ridge": Pipeline([("scale", StandardScaler()), ("reg", Ridge(alpha=1.0))]),
        "random_forest": RandomForestRegressor(n_estimators=80, max_depth=12, min_samples_leaf=4, random_state=seed, n_jobs=1),
        "hist_gb": HistGradientBoostingRegressor(max_depth=6, learning_rate=0.05, max_iter=150, random_state=seed),
    }


def _ranking_metrics(rows, preds) -> Dict[str, float]:
    grouped: Dict[str, List[Tuple[Dict[str, object], float]]] = {}
    for row, pred in zip(rows, preds):
        grouped.setdefault(str(row["decision_id"]), []).append((row, float(pred)))
    top1, regrets = 0, []
    for items in grouped.values():
        chosen = min(items, key=lambda x: (x[1], str(x[0]["candidate_page_id"])))
        best = min(items, key=lambda x: (float(x[0]["eviction_loss_label"]), str(x[0]["candidate_page_id"])))
        top1 += int(chosen[0]["candidate_page_id"] == best[0]["candidate_page_id"])
        regrets.append(float(chosen[0]["eviction_loss_label"]) - float(best[0]["eviction_loss_label"]))
    denom = max(len(grouped), 1)
    return {"top1_eviction_match": top1 / denom, "mean_regret_vs_oracle": float(np.mean(regrets) if regrets else 0.0)}


def _train_scalar(train_rows, val_rows, seed: int) -> Tuple[EvictValueV1Model, str]:
    x_train = np.asarray([[float(r[c]) for c in FEATURES] for r in train_rows], dtype=float)
    y_train = np.asarray([float(r["eviction_loss_label"]) for r in train_rows], dtype=float)
    x_val = np.asarray([[float(r[c]) for c in FEATURES] for r in val_rows], dtype=float)
    y_val = np.asarray([float(r["eviction_loss_label"]) for r in val_rows], dtype=float)

    models = _scalar_model_family(seed)
    best_name, best_est, best_key = None, None, None
    for name, est in models.items():
        est.fit(x_train, y_train)
        p_val = est.predict(x_val)
        mae = mean_absolute_error(y_val, p_val)
        rmse = float(np.sqrt(mean_squared_error(y_val, p_val)))
        r = _ranking_metrics(val_rows, p_val)
        key = (r["mean_regret_vs_oracle"], mae, rmse)
        if best_key is None or key < best_key:
            best_key, best_name, best_est = key, name, est
    return EvictValueV1Model(model_name=best_name, estimator=best_est, feature_columns=FEATURES), best_name


def _reservoir_sample_stream(stream, max_rows: int, seed: int) -> List[Dict[str, object]]:
    """Algorithm R reservoir sampling over a row generator: bounds peak
    memory to max_rows regardless of stream length, while giving every row
    an equal chance of retention (uniform, seeded, deterministic).

    Necessary because a single 50k-request trace at capacity=128 can
    generate ~1.5-6M+ candidate rows, and this module pools rows across 3
    capacities x 5-6 training families x 2 DAgger iterations in memory --
    an unbounded list here would very plausibly reproduce the 57GB OOM
    crash documented in scripts/build_supervision_objective_ablation_dataset.py's
    module docstring (same underlying failure mode: an uncapped in-memory
    row list at full trace scale)."""
    import random

    rng = random.Random(seed)
    reservoir: List[Dict[str, object]] = []
    for i, row in enumerate(stream):
        if len(reservoir) < max_rows:
            reservoir.append(row)
        else:
            j = rng.randint(0, i)
            if j < max_rows:
                reservoir[j] = row
    return reservoir


def _collect_rows(family_recs: List[Dict[str, str]], split_map: Dict[str, str], capacity: int,
                   behavior_model, behavior_policy_name: str, cfg: DistributionShiftConfig,
                   max_requests_per_trace: int = 0, data_read_root: Path = Path("."),
                   max_rows_per_trace: int = 60000, seed: int = 0) -> List[Dict[str, object]]:
    rows: List[Dict[str, object]] = []
    for rec in family_recs:
        family = rec["trace_family"]
        split = split_map[family]
        reqs, _pages, _src = load_trace_from_any(str(data_read_root / rec["path"]))
        if max_requests_per_trace:
            reqs = reqs[:max_requests_per_trace]
        stream = iter_candidate_rows_with_behavior_policy(
            reqs, capacity, rec["trace_name"], family, cfg,
            behavior_model=behavior_model, behavior_policy_name=behavior_policy_name,
        )
        sampled = _reservoir_sample_stream(stream, max_rows_per_trace, seed)
        for row in sampled:
            row["split"] = split
        rows.extend(sampled)
    return rows


def _split_train_val(rows: List[Dict[str, object]]) -> Tuple[List[Dict[str, object]], List[Dict[str, object]]]:
    return [r for r in rows if r["split"] == "train"], [r for r in rows if r["split"] == "val"]


class TimeBudget:
    def __init__(self, max_wall_hours: float):
        self.start = time.time()
        self.max_seconds = max_wall_hours * 3600.0
        self.unit_costs: List[float] = []

    def remaining(self) -> float:
        return self.max_seconds - (time.time() - self.start)

    def avg_unit_cost(self) -> float:
        return float(np.mean(self.unit_costs)) if self.unit_costs else 0.0

    def can_start_new_unit(self) -> bool:
        if not self.unit_costs:
            return True
        return self.remaining() > self.avg_unit_cost()

    def record_unit(self, seconds: float) -> None:
        self.unit_costs.append(seconds)


def _collect_rows_pooled(recs, split_map, capacities: List[int], behavior_model, behavior_policy_name: str,
                          cfg: DistributionShiftConfig, max_requests_per_trace: int = 0,
                          data_read_root: Path = Path("."), max_rows_per_trace: int = 60000,
                          seed: int = 0) -> List[Dict[str, object]]:
    """Pool candidate rows across ALL capacities (matches the canonical
    evict_value_v1 pipeline's convention: one shared model trained on rows
    from every capacity, not one model per capacity -- see
    scripts/build_evict_value_dataset_wulver_v1.py's --capacities loop
    feeding a single train/val/test split). Each (trace, capacity) is
    independently reservoir-sampled to max_rows_per_trace (see
    _reservoir_sample_stream) -- bounds total memory regardless of trace
    length or capacity."""
    rows: List[Dict[str, object]] = []
    for cap in capacities:
        rows.extend(_collect_rows(recs, split_map, cap, behavior_model, behavior_policy_name, cfg,
                                   max_requests_per_trace, data_read_root, max_rows_per_trace, seed))
    return rows


def _run_fold(
    family: str, capacities: List[int], models_dir: Path, seed: int,
    policy_writer: IncrementalCsvWriter, shift_writer: IncrementalCsvWriter, traj_writer: IncrementalCsvWriter,
    state_path: Path, max_requests_per_trace: int = 0, data_read_root: Path = Path("."),
    max_rows_per_trace: int = 60000,
) -> None:
    fold = _load_fold(family)
    split_map = _load_split_map(family)
    recs = _load_train_manifest(family)
    cfg = DistributionShiftConfig(horizon=HORIZON)

    test_trace_path = data_read_root / fold["test_trace_path"]
    if not test_trace_path.exists():
        raise FileNotFoundError(f"Held-out trace not found: {test_trace_path}")
    trace_hash = sha256_of_file(test_trace_path)
    if fold.get("test_trace_sha256") and trace_hash != fold["test_trace_sha256"]:
        raise ValueError(f"Fold {family}: trace hash mismatch")
    held_out_reqs, held_out_pages, _src = load_trace_from_any(str(test_trace_path))

    models_dir.mkdir(parents=True, exist_ok=True)

    # ---- OFF_POLICY_LRU: build (pooled across capacities) + train ----
    off_policy_model_path = models_dir / "OFF_POLICY_LRU" / f"{family}.pkl"
    rows_off_full = _collect_rows_pooled(recs, split_map, capacities, None, "lru", cfg, max_requests_per_trace,
                                          data_read_root, max_rows_per_trace, seed)
    train_off, val_off = _split_train_val(rows_off_full)
    if off_policy_model_path.exists():
        off_model = EvictValueV1Model.load(off_policy_model_path)
    else:
        off_model, off_name = _train_scalar(train_off, val_off, seed)
        off_policy_model_path.parent.mkdir(parents=True, exist_ok=True)
        off_model.save(off_policy_model_path)
        print(f"[trained] OFF_POLICY_LRU fold={family}: best={off_name} n_train={len(train_off)} n_val={len(val_off)}")

    # ---- DAGGER_ITER1: iter1 states under frozen off_model (train+val
    # families only, held-out never touched), D_train = D0 union D1,
    # retrain; validation stays iter0's off-policy validation rows (model
    # selection must never depend on the condition being tested). ----
    dagger_model_path = models_dir / "DAGGER_ITER1" / f"{family}.pkl"
    rows_iter1_full = _collect_rows_pooled(
        recs, split_map, capacities, off_model, "learned_argmin_frozen_iter0_model", cfg,
        max_requests_per_trace, data_read_root, max_rows_per_trace, seed + 1,
    )
    train_iter1, _val_iter1_unused = _split_train_val(rows_iter1_full)
    d_train = list(train_off) + list(train_iter1)
    if dagger_model_path.exists():
        dagger_model = EvictValueV1Model.load(dagger_model_path)
    else:
        dagger_model, dagger_name = _train_scalar(d_train, val_off, seed)
        dagger_model_path.parent.mkdir(parents=True, exist_ok=True)
        dagger_model.save(dagger_model_path)
        print(f"[trained] DAGGER_ITER1 fold={family}: best={dagger_name} n_train={len(d_train)} n_val={len(val_off)}")

    models_by_condition = {"OFF_POLICY_LRU": off_model, "DAGGER_ITER1": dagger_model}
    model_paths = {"OFF_POLICY_LRU": off_policy_model_path, "DAGGER_ITER1": dagger_model_path}
    train_rows_by_condition = {"OFF_POLICY_LRU": train_off, "DAGGER_ITER1": d_train}

    # ---- Held-out evaluation + diagnostics, per condition x capacity ----
    for condition in CONDITIONS:
        model = models_by_condition[condition]
        model_hash = sha256_of_file(model_paths[condition])
        for cap in capacities:
            key = {"condition": condition, "held_out_family": family, "capacity": cap}
            if policy_writer.already_done(key):
                continue
            try:
                t0 = time.time()
                policy = DistributionShiftEvalPolicy(model_path=str(model_paths[condition]))
                result = run_policy(policy, held_out_reqs, held_out_pages, cap)
                wall_s = time.time() - t0
                primary = score_window(result.events, SCORE_START, len(result.events))

                deploy_rows_scored = [r for r in policy.deployment_state_rows if r["decision_t"] >= SCORE_START]
                # Training-state distribution for THIS condition, filtered
                # to the capacity being evaluated (rows already pooled
                # across capacities were tagged with their own "capacity"
                # column at collection time -- no rebuild needed).
                cond_train_rows = [r for r in train_rows_by_condition[condition] if int(r["capacity"]) == cap]

                shift = compute_state_shift(cond_train_rows, deploy_rows_scored) if deploy_rows_scored and cond_train_rows else None
                shift_idx = shift.aggregate_state_shift_index if shift else float("nan")

                ref_reqs = held_out_reqs
                traj = compute_trajectory_divergence(ref_reqs, cap, reference_model=None, other_model=model)

                row = {
                    "experiment_protocol_version": PROTOCOL_VERSION,
                    "policy": f"distribution_shift_{condition}", "policy_variant": "primary_controlled_window",
                    "implementation_source": "native_pretrained_offline", "implementation_commit": "n/a",
                    "trace": fold["test_trace_name"], "trace_sha256": trace_hash,
                    "capacity": cap, "capacity_semantics": "object_slots", "object_size_semantics": "unit",
                    "history_start": HISTORY_START, "history_end": HISTORY_END,
                    "score_start": primary.score_start, "score_end": primary.score_end,
                    "history_requests": primary.history_requests, "scored_requests": primary.scored_requests,
                    "hits": primary.hits, "misses": primary.misses, "miss_ratio": round(primary.miss_ratio, 6),
                    "cache_warmup": f"processes_[{HISTORY_START},{HISTORY_END})_then_scores_[{SCORE_START},{SCORE_END})",
                    "model_training_mode": "offline_pretrained_frozen_cross_family",
                    "model_training_data": f"condition={condition}; 5 training families ({','.join(fold['training_families'])}), "
                    f"validation family={fold['validation_family']}, held-out family={family} contributes ZERO rows",
                    "model_frozen_during_test": "yes", "online_adaptation_during_test": "no",
                    "hyperparameter_source": "frozen_distribution_shift_ablation_v1_grid",
                    "random_seed": str(seed), "future_information": "none",
                    "runtime_seconds": round(wall_s, 4), "status": "ok", "failure_reason": "",
                    "protocol_id": "distribution_shift_ablation_v1", "condition": condition,
                    "held_out_family": family, "fold_id": fold["fold_id"], "model_hash": model_hash,
                    "state_shift_index": round(shift_idx, 6) if shift_idx == shift_idx else "",
                    "first_divergence_index": traj.first_divergence_index if traj.first_divergence_index is not None else "",
                    "fraction_decisions_diverged_from_lru": round(traj.fraction_decisions_diverged, 6),
                    "mean_cache_set_jaccard_similarity": round(traj.mean_cache_set_jaccard_similarity, 6),
                }
                validate_common_row(row)
                policy_writer.write_row(row)

                shift_key = {"condition": condition, "held_out_family": family, "capacity": cap}
                if not shift_writer.already_done(shift_key):
                    shift_writer.write_row({
                        "protocol_id": "distribution_shift_ablation_v1", "condition": condition,
                        "held_out_family": family, "capacity": cap,
                        "aggregate_state_shift_index": round(shift_idx, 6) if shift_idx == shift_idx else "",
                        "n_train_rows": len(cond_train_rows), "n_deploy_rows": len(deploy_rows_scored),
                    })

                if condition == "DAGGER_ITER1":
                    traj_key = {"held_out_family": family, "capacity": cap, "reference_condition": "OFF_POLICY_LRU", "other_condition": "DAGGER_ITER1"}
                    if not traj_writer.already_done(traj_key):
                        traj_ab = compute_trajectory_divergence(ref_reqs, cap, reference_model=off_model, other_model=dagger_model)
                        traj_writer.write_row({
                            "protocol_id": "distribution_shift_ablation_v1", "held_out_family": family, "capacity": cap,
                            "reference_condition": "OFF_POLICY_LRU", "other_condition": "DAGGER_ITER1",
                            "first_divergence_index": traj_ab.first_divergence_index if traj_ab.first_divergence_index is not None else "",
                            "fraction_decisions_diverged": round(traj_ab.fraction_decisions_diverged, 6),
                            "mean_cache_set_jaccard_similarity": round(traj_ab.mean_cache_set_jaccard_similarity, 6),
                            "longest_identical_prefix_length": traj_ab.longest_identical_prefix_length,
                            "distinct_states_reference": traj_ab.distinct_cache_states_visited_reference,
                            "distinct_states_other": traj_ab.distinct_cache_states_visited_other,
                        })

                print(f"[eval] condition={condition} family={family} cap={cap}: misses={primary.misses}/{primary.scored_requests} "
                      f"shift_idx={shift_idx:.4f} ({wall_s:.1f}s)")
            except Exception as exc:  # noqa: BLE001
                row = {f: "" for f in POLICY_FIELDNAMES}
                row.update({
                    "experiment_protocol_version": PROTOCOL_VERSION,
                    "policy": f"distribution_shift_{condition}", "policy_variant": "primary_controlled_window",
                    "trace": fold["test_trace_name"], "capacity": cap,
                    "status": "failed", "failure_reason": f"{type(exc).__name__}: {exc}",
                    "protocol_id": "distribution_shift_ablation_v1", "condition": condition,
                    "held_out_family": family, "fold_id": fold["fold_id"],
                })
                policy_writer.write_row(row)
                print(f"[FAIL] condition={condition} family={family} cap={cap}: {exc}", file=sys.stderr)
                traceback.print_exc()

    state_payload = json.loads(state_path.read_text()) if state_path.exists() else {"completed_folds": []}
    if family not in state_payload["completed_folds"]:
        state_payload["completed_folds"].append(family)
    state_payload["last_update_unix"] = time.time()
    state_path.write_text(json.dumps(state_payload, indent=2), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default="configs/distribution_shift_ablation_v1.json")
    ap.add_argument("--capacities", default="32,64,128")
    ap.add_argument("--max-wall-hours", type=float, default=9.0)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--models-dir", type=Path, default=Path("models/distribution_shift_ablation_v1"))
    ap.add_argument("--out-dir", type=Path, default=Path("analysis/distribution_shift_ablation_v1"))
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("--max-requests-per-trace", type=int, default=0,
                     help="Optional prefix cap on TRAINING-family traces only (smoke testing). "
                     "Held-out evaluation always uses the full trace (fixed history/score windows).")
    ap.add_argument("--data-read-root", type=Path, default=Path("."),
                     help="Root to resolve fold trace paths against (this worktree's data/processed/ "
                     "is empty by design; point at the checkout that has the canonical traces).")
    ap.add_argument("--max-rows-per-trace", type=int, default=60000,
                     help="Reservoir-sampling cap on candidate rows collected per (trace, capacity) "
                     "combination -- resource-safety measure, applied identically to both conditions. "
                     "Prevents the uncapped-in-memory-list OOM failure mode seen in the canonical "
                     "single-objective pipeline at full trace scale.")
    args = ap.parse_args()

    config = json.loads(Path(args.config).read_text(encoding="utf-8"))
    if config["protocol_id"] != "distribution_shift_ablation_v1":
        raise ValueError("Config protocol_id mismatch -- refusing to run against an unexpected protocol.")

    capacities = [int(x) for x in args.capacities.split(",") if x.strip()]
    args.out_dir.mkdir(parents=True, exist_ok=True)

    policy_writer = IncrementalCsvWriter(args.out_dir / "policy_comparison.csv", POLICY_FIELDNAMES, POLICY_KEY_FIELDS)
    shift_writer = IncrementalCsvWriter(args.out_dir / "state_shift_metrics.csv", SHIFT_FIELDNAMES, SHIFT_KEY_FIELDS)
    traj_writer = IncrementalCsvWriter(args.out_dir / "trajectory_divergence.csv", TRAJ_FIELDNAMES, TRAJ_KEY_FIELDS)
    state_path = args.out_dir / "campaign_state.json"

    budget = TimeBudget(args.max_wall_hours)
    (args.out_dir / "protocol_snapshot.json").write_text(json.dumps(config, indent=2), encoding="utf-8")

    for family in FAMILIES:
        state_payload = json.loads(state_path.read_text()) if state_path.exists() else {"completed_folds": []}
        if family in state_payload.get("completed_folds", []):
            print(f"[skip] fold={family} already completed (resume)")
            continue
        if not budget.can_start_new_unit():
            print(f"[budget] remaining={budget.remaining():.0f}s < avg_unit_cost={budget.avg_unit_cost():.0f}s -- "
                  f"stopping before starting fold={family}")
            break
        t0 = time.time()
        try:
            _run_fold(family, capacities, args.models_dir, args.seed, policy_writer, shift_writer, traj_writer,
                      state_path, args.max_requests_per_trace, args.data_read_root, args.max_rows_per_trace)
        except Exception as exc:  # noqa: BLE001
            print(f"[FOLD FAIL] {family}: {exc}", file=sys.stderr)
            traceback.print_exc()
        budget.record_unit(time.time() - t0)

    policy_writer.close()
    shift_writer.close()
    traj_writer.close()
    provenance = {**base_provenance(), "protocol_id": "distribution_shift_ablation_v1", "max_wall_hours": args.max_wall_hours}
    write_provenance_json(args.out_dir / "provenance.json", provenance)
    print(f"Campaign pass complete. Outputs under {args.out_dir}/")


if __name__ == "__main__":
    main()
