"""Distribution-shift ablation campaign runner
(docs/distribution_shift_ablation_protocol.md,
configs/distribution_shift_ablation_v1.json).

For each of the 7 leave-one-family-out folds (reviewer_fair_cross_family_v1,
unchanged), trains and held-out-evaluates 2 conditions:

  OFF_POLICY_LRU: states generated by LRU trajectory (characterizes
    existing dataset-builder behavior).
  DAGGER_ITER1: iteration-0 = OFF_POLICY_LRU; iteration-1 additionally
    collects states visited under the frozen iteration-0 model's own
    argmin decisions on training+validation families only, aggregated
    with iteration-0's states, retrained.

Ground-truth labels are always the frozen finite-horizon L_H
(_simulate_lru_misses), independent of which policy generated the state
(anti-circularity, protocol Section 7).

Checkpointed per fold x condition; resumable (skips completed, hash-valid
units); time-budgeted (--max-wall-hours, default 9): stops launching NEW
folds once remaining budget is below the observed average fold cost, never
truncates a fold mid-write.
"""

